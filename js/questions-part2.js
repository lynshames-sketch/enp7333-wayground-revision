    // On place la bonne réponse de façon cyclique/aléatoire équilibrée sur les indices 0, 1, 2, 3 dans la banque de base
    const targetSlot = idx % 4;
    const wrongOptions = q.options.filter(opt => opt !== q.correctAnswer);
